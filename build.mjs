// MARK: - JSON

StyleDictionary.registerFormat({
  name: 'briareus/json',
  format: ({ dictionary }) => {
    const tree = {};
    for (const t of dictionary.allTokens) {
      let node = tree;
      t.path.slice(0, -1).forEach((p) => (node = node[p] ??= {}));
      node[leaf(t)] = t.$extensions?.briareus?.statuses ? { role: value(t), statuses: t.$extensions.briareus.statuses } : value(t);
    }
    return JSON.stringify(tree, null, 2) + '\n';
  },
});

