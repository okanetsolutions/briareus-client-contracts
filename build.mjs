// MARK: - Reading resolved tokens

const value = (t) => t.$value ?? t.value;
const under = (dictionary, ...prefix) =>
  dictionary.allTokens.filter((t) => prefix.every((p, i) => t.path[i] === p));
const leaf = (t) => t.path[t.path.length - 1];
const px = (v) => (typeof v === 'number' ? v : typeof v === 'object' ? Number(v.value) : parseFloat(v));
const ms = (v) => (typeof v === 'object' ? (v.unit === 's' ? v.value * 1000 : v.value) : v.endsWith('ms') ? parseFloat(v) : parseFloat(v) * 1000);
const hex = (v) => v.replace('#', '').toUpperCase();

/// The theme roles in the order dark.json lists them; light must list the same ones.
function themes(dictionary) {
  const dark = under(dictionary, 'theme', 'dark');
  const light = new Map(under(dictionary, 'theme', 'light').map((t) => [leaf(t), t]));
  const roles = dark.map(leaf);
  const missing = roles.filter((r) => !light.has(r));
  if (missing.length || light.size !== roles.length) throw new Error(`theme.light and theme.dark disagree: ${missing.join(', ') || 'extra light roles'}`);
  return roles.map((role, i) => ({ role, dark: hex(value(dark[i])), light: hex(value(light.get(role))), description: dark[i].$description }));
}

function statuses(dictionary) {
  return under(dictionary, 'status').map((t) => ({
    name: leaf(t),
    role: value(t),
    statuses: t.$extensions?.briareus?.statuses ?? [],
    description: t.$description,
  }));
}

function textStyles(dictionary, ...prefix) {
  return under(dictionary, ...prefix).map((t) => {
    const v = value(t);
    return {
      name: leaf(t),
      size: px(v.fontSize),
      weight: Number(v.fontWeight),
      italic: v.fontStyle === 'italic',
      mono: v.fontFamily === 'mono',
      lineHeight: v.lineHeight ? px(v.lineHeight) : null,
    };
  });
}

const dimensions = (dictionary, group) => under(dictionary, group).map((t) => ({ name: leaf(t), px: px(value(t)), description: t.$description }));
const content = (dictionary) => ({
  glyphs: value(under(dictionary, 'working', 'glyphs')[0]),
  verbs: value(under(dictionary, 'working', 'verbs')[0]),
  verbTicks: value(under(dictionary, 'working', 'verbTicks')[0]),
  pulseMs: ms(value(under(dictionary, 'motion', 'pulse')[0])),
});

/// The chart colours: the series (one set for both modes) and the context bar's categories per mode, with how a
/// category name picks each.
function chart(dictionary) {
  const series = under(dictionary, 'chart', 'series');
  const dark = under(dictionary, 'chart', 'context', 'dark');
  const light = new Map(under(dictionary, 'chart', 'context', 'light').map((t) => [leaf(t), t]));
  const context = dark.map((t) => {
    const l = light.get(leaf(t));
    if (!l) throw new Error(`chart.context.light has no ${leaf(t)}`);
    const rule = t.$extensions?.briareus ?? {};
    return { name: leaf(t), dark: hex(value(t)), light: hex(value(l)), equals: rule.equals ?? [], contains: rule.contains ?? [], description: t.$description };
  });
  if (!context.some((c) => c.name === 'unknown')) throw new Error('chart.context needs an unknown colour');
  return {
    series: series.filter((t) => leaf(t) !== 'other').map((t) => hex(value(t))),
    other: hex(value(series.find((t) => leaf(t) === 'other'))),
    context,
  };
}

const upperSnake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
const lowerSnake = (s) => upperSnake(s).toLowerCase();
const quote = (s) => JSON.stringify(s);

