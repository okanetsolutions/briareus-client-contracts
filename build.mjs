// Builds dist/ from tokens/: one file per client platform, all from the same resolved tokens.
// Style Dictionary resolves the references; the formats below write each platform's own idiom.
import { rm } from 'node:fs/promises';
import StyleDictionary from 'style-dictionary';

const HEADER = 'Generated by briareus-tokens (https://github.com/okanetsolutions/briareus-tokens) from tokens/. Do not edit: change the tokens and run `npm run build`.';

// MARK: - Reading resolved tokens

const value = (t) => t.$value ?? t.value;
const under = (dictionary, ...prefix) =>
  dictionary.allTokens.filter((t) => prefix.every((p, i) => t.path[i] === p));
const leaf = (t) => t.path[t.path.length - 1];
const px = (v) => (typeof v === 'number' ? v : typeof v === 'object' ? Number(v.value) : parseFloat(v));
const ms = (v) => (typeof v === 'object' ? (v.unit === 's' ? v.value * 1000 : v.value) : v.endsWith('ms') ? parseFloat(v) : parseFloat(v) * 1000);
const hex = (v) => v.replace('#', '').toUpperCase();

/// The theme roles in the order dark.json lists them; light must list the same ones.
function themes(dictionary) {
  const dark = under(dictionary, 'theme', 'dark');
  const light = new Map(under(dictionary, 'theme', 'light').map((t) => [leaf(t), t]));
  const roles = dark.map(leaf);
  const missing = roles.filter((r) => !light.has(r));
  if (missing.length || light.size !== roles.length) throw new Error(`theme.light and theme.dark disagree: ${missing.join(', ') || 'extra light roles'}`);
  return roles.map((role, i) => ({ role, dark: hex(value(dark[i])), light: hex(value(light.get(role))), description: dark[i].$description }));
}

function statuses(dictionary) {
  return under(dictionary, 'status').map((t) => ({
    name: leaf(t),
    role: value(t),
    statuses: t.$extensions?.briareus?.statuses ?? [],
    description: t.$description,
  }));
}

function textStyles(dictionary, ...prefix) {
  return under(dictionary, ...prefix).map((t) => {
    const v = value(t);
    return {
      name: leaf(t),
      size: px(v.fontSize),
      weight: Number(v.fontWeight),
      italic: v.fontStyle === 'italic',
      mono: v.fontFamily === 'mono',
      lineHeight: v.lineHeight ? px(v.lineHeight) : null,
    };
  });
}

const dimensions = (dictionary, group) => under(dictionary, group).map((t) => ({ name: leaf(t), px: px(value(t)), description: t.$description }));
const content = (dictionary) => ({
  glyphs: value(under(dictionary, 'working', 'glyphs')[0]),
  verbs: value(under(dictionary, 'working', 'verbs')[0]),
  verbTicks: value(under(dictionary, 'working', 'verbTicks')[0]),
  pulseMs: ms(value(under(dictionary, 'motion', 'pulse')[0])),
});

const upperSnake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
const lowerSnake = (s) => upperSnake(s).toLowerCase();
const quote = (s) => JSON.stringify(s);

// MARK: - Kotlin (Jetpack Compose)

StyleDictionary.registerFormat({
  name: 'briareus/compose',
  format: ({ dictionary, options }) => {
    const roles = themes(dictionary);
    const status = statuses(dictionary);
    const c = content(dictionary);
    const palette = (mode) => roles.map((r) => `${r.role} = Color(0xFF${r[mode]})`).join(', ');
    const style = (s) => {
      const args = [`fontSize = ${s.size}.sp`];
      if (s.lineHeight) args.push(`lineHeight = ${s.lineHeight}.sp`);
      args.push(`fontWeight = FontWeight(${s.weight})`);
      if (s.italic) args.push('fontStyle = FontStyle.Italic');
      if (s.mono) args.push('fontFamily = FontFamily.Monospace');
      return `    val ${s.name} = TextStyle(${args.join(', ')})`;
    };
    const dims = (group) => dimensions(dictionary, group).map((d) => `    val ${d.name} = ${d.px}.dp`).join('\n');
    return `// ${HEADER}
@file:Suppress("MagicNumber", "MaxLineLength")

package ${options.packageName}

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/** The theme's colours, one value per role. */
@Immutable
data class BriareusPalette(
${roles.map((r) => `    val ${r.role}: Color,`).join('\n')}
) {
    companion object {
        val Dark = BriareusPalette(${palette('dark')})
        val Light = BriareusPalette(${palette('light')})
    }

    /** The colour a status role takes. */
    fun color(role: StatusRole): Color = when (role) {
${status.map((s) => `        StatusRole.${upperSnake(s.name)} -> ${s.role}`).join('\n')}
    }

    /** A session status dot's colour, from the server's status string. */
    fun statusColor(status: String?): Color = color(StatusRole.of(status))
}

/** What a session's status dot says. */
enum class StatusRole {
${status.map((s) => `    ${upperSnake(s.name)},`).join('\n')}
    ;

    companion object {
        fun of(status: String?): StatusRole = when (status) {
${status.filter((s) => s.statuses.length).map((s) => `            ${s.statuses.map(quote).join(', ')} -> ${upperSnake(s.name)}`).join('\n')}
            else -> INACTIVE
        }
    }
}

/** Desktop text styles, in sp. */
object BriareusType {
${textStyles(dictionary, 'type').map(style).join('\n')}
}

/** Text styles for a headset panel a metre away, by Material 3 role. */
object BriareusHeadsetType {
${textStyles(dictionary, 'headset', 'type').map(style).join('\n')}
}

object BriareusRadius {
${dims('radius')}
}

object BriareusLayout {
${dims('layout')}
}

object BriareusMotion {
    const val PULSE_MILLIS = ${c.pulseMs}
}

/** The working indicator: a glyph per tick, a verb every ${c.verbTicks} ticks. */
object BriareusWorking {
    val glyphs = listOf(${c.glyphs.map(quote).join(', ')})
    val verbs = listOf(${c.verbs.map(quote).join(', ')})
    fun glyph(tick: Int): String = glyphs[tick.mod(glyphs.size)]
    fun verb(tick: Int): String = verbs[(tick / ${c.verbTicks}).mod(verbs.size)]
}
`;
  },
});

// MARK: - Swift

StyleDictionary.registerFormat({
  name: 'briareus/swift',
  format: ({ dictionary }) => {
    const roles = themes(dictionary);
    const status = statuses(dictionary);
    const c = content(dictionary);
    const palette = (mode) => roles.map((r) => `${r.role}: 0x${r[mode]}`).join(', ');
    const style = (s) =>
      `    public static let ${s.name} = BriareusTextStyle(size: ${s.size}, weight: ${s.weight}${s.italic ? ', italic: true' : ''}${s.mono ? ', monospaced: true' : ''}${s.lineHeight ? `, lineHeight: ${s.lineHeight}` : ''})`;
    const dims = (group) =>
      dimensions(dictionary, group).map((d) => `${d.description ? `    /// ${d.description}\n` : ''}    public static let ${d.name}: Double = ${d.px}`).join('\n');
    return `// ${HEADER}
// Plain values with no UIKit, AppKit or SwiftUI, so the core can carry them: each app turns the 0xRRGGBB colours into its own
// dynamic colour and the text styles into its own fonts.

/// The theme's colours as 0xRRGGBB, one value per role.
public struct BriareusPalette: Sendable, Equatable {
${roles.map((r) => `${r.description ? `    /// ${r.description}\n` : ''}    public let ${r.role}: UInt32`).join('\n')}

    public static let dark = BriareusPalette(${palette('dark')})
    public static let light = BriareusPalette(${palette('light')})

    /// The colour a status role takes.
    public func color(for role: BriareusStatusRole) -> UInt32 {
        switch role {
${status.map((s) => `        case .${s.name}: return ${s.role}`).join('\n')}
        }
    }
}

/// What a session's status dot says.
public enum BriareusStatusRole: String, Sendable, CaseIterable {
${status.map((s) => `${s.description ? `    /// ${s.description}\n` : ''}    case ${s.name}`).join('\n')}

    /// The role of a server status string; one this version does not know is \`inactive\`.
    public init(status: String?) {
        switch status {
${status.filter((s) => s.statuses.length).map((s) => `        case ${s.statuses.map(quote).join(', ')}: self = .${s.name}`).join('\n')}
        default: self = .inactive
        }
    }
}

/// A text style: size in points, weight as CSS numbers (400 regular, 500 medium, 600 semibold).
public struct BriareusTextStyle: Sendable, Equatable {
    public let size: Double
    public let weight: Int
    public let italic: Bool
    public let monospaced: Bool
    public let lineHeight: Double?

    public init(size: Double, weight: Int, italic: Bool = false, monospaced: Bool = false, lineHeight: Double? = nil) {
        self.size = size; self.weight = weight; self.italic = italic; self.monospaced = monospaced; self.lineHeight = lineHeight
    }
}

public enum BriareusType {
${textStyles(dictionary, 'type').map(style).join('\n')}
}

public enum BriareusRadius {
${dims('radius')}
}

public enum BriareusLayout {
${dims('layout')}
}

public enum BriareusMotion {
    /// A running status dot's ring, in seconds.
    public static let pulse: Double = ${c.pulseMs / 1000}
}

/// The working indicator: a glyph per tick, a verb every ${c.verbTicks} ticks.
public enum BriareusWorking {
    public static let glyphs = [${c.glyphs.map(quote).join(', ')}]
    public static let verbs = [${c.verbs.map(quote).join(', ')}]
    public static func glyph(_ tick: Int) -> String { glyphs[((tick % glyphs.count) + glyphs.count) % glyphs.count] }
    public static func verb(_ tick: Int) -> String { verbs[((tick / ${c.verbTicks}) % verbs.count + verbs.count) % verbs.count] }
}
`;
  },
});

// MARK: - C (Win32)

StyleDictionary.registerFormat({
  name: 'briareus/c',
  format: ({ dictionary }) => {
    const roles = themes(dictionary);
    const status = statuses(dictionary);
    const c = content(dictionary);
    const families = under(dictionary, 'font', 'family', 'windows');
    const palette = (mode) => roles.map((r) => `    .${lowerSnake(r.role)} = 0x${r[mode]},`).join('\n');
    const style = (s) => `static const BriareusTextStyle BRIAREUS_TYPE_${upperSnake(s.name)} = { ${s.size}, ${s.weight}, ${s.italic}, ${s.mono} };`;
    const dims = (group) => dimensions(dictionary, group).map((d) => `#define BRIAREUS_${upperSnake(group)}_${upperSnake(d.name)} ${d.px}`).join('\n');
    const wide = (s) => `L${quote(s)}`;
    return `// ${HEADER}
// Header-only C11. Colours are 0xRRGGBB (not COLORREF's 0x00BBGGRR); sizes are px at 96 DPI.
#ifndef BRIAREUS_TOKENS_H
#define BRIAREUS_TOKENS_H
#include <stdbool.h>
#include <stddef.h>
#include <string.h>
#include <wchar.h>

#ifdef __cplusplus
extern "C" {
#endif

typedef struct {
${roles.map((r) => `    unsigned int ${lowerSnake(r.role)};${r.description ? `   // ${r.description}` : ''}`).join('\n')}
} BriareusPalette;

static const BriareusPalette BRIAREUS_PALETTE_DARK = {
${palette('dark')}
};

static const BriareusPalette BRIAREUS_PALETTE_LIGHT = {
${palette('light')}
};

typedef enum {
${status.map((s) => `    BRIAREUS_STATUS_${upperSnake(s.name)},`).join('\n')}
} BriareusStatusRole;

/// The role of a server status string; NULL or one this version does not know is inactive.
static inline BriareusStatusRole briareus_status_role(const char *status) {
    if (!status) return BRIAREUS_STATUS_INACTIVE;
${status.filter((s) => s.statuses.length && s.name !== 'inactive').map((s) => `    if (${s.statuses.map((x) => `strcmp(status, ${quote(x)}) == 0`).join(' || ')}) return BRIAREUS_STATUS_${upperSnake(s.name)};`).join('\n')}
    return BRIAREUS_STATUS_INACTIVE;
}

static inline unsigned int briareus_status_color(const BriareusPalette *palette, BriareusStatusRole role) {
    switch (role) {
${status.map((s) => `    case BRIAREUS_STATUS_${upperSnake(s.name)}: return palette->${lowerSnake(s.role)};`).join('\n')}
    }
    return palette->dot;
}

typedef struct {
    int size;      // px at 96 DPI
    int weight;    // 400 regular, 500 medium, 600 semibold (FW_ values)
    bool italic;
    bool mono;
} BriareusTextStyle;

${textStyles(dictionary, 'type').map(style).join('\n')}

// Font families in order of preference, NULL-terminated.
${families.map((t) => `static const wchar_t *const BRIAREUS_FONT_${upperSnake(leaf(t))}[] = { ${value(t).map(wide).join(', ')}, NULL };`).join('\n')}

${dims('radius')}

${dims('layout')}

#define BRIAREUS_MOTION_PULSE_MS ${c.pulseMs}

#define BRIAREUS_WORKING_VERB_TICKS ${c.verbTicks}
static const wchar_t *const BRIAREUS_WORKING_GLYPHS[] = { ${c.glyphs.map(wide).join(', ')} };
static const char *const BRIAREUS_WORKING_VERBS[] = { ${c.verbs.map(quote).join(', ')} };

#ifdef __cplusplus
}
#endif

#endif
`;
  },
});

// MARK: - CSS

StyleDictionary.registerFormat({
  name: 'briareus/css',
  format: ({ dictionary }) => {
    const roles = themes(dictionary);
    const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
    const colors = (mode, indent) => roles.map((r) => `${indent}--br-${kebab(r.role)}: #${r[mode]};`).join('\n');
    const dims = (group) => dimensions(dictionary, group).map((d) => `  --br-${group}-${kebab(d.name)}: ${d.px}px;`).join('\n');
    const sizes = under(dictionary, 'font', 'size').map((t) => `  --br-font-${kebab(leaf(t))}: ${px(value(t))}px;`).join('\n');
    const family = (name) => value(under(dictionary, 'font', 'family', 'web', name)[0]).map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ');
    const status = statuses(dictionary).map((s) => `  --br-status-${s.name}: var(--br-${kebab(s.role)});`).join('\n');
    return `/* ${HEADER} */
/* Light unless the system prefers dark; data-theme="light" or "dark" on <html> overrides either way. */
:root {
  color-scheme: light dark;
${colors('light', '  ')}
${status}
  --br-font-sans: ${family('sans')};
  --br-font-mono: ${family('mono')};
${sizes}
${dims('radius')}
${dims('layout')}
  --br-motion-pulse: ${content(dictionary).pulseMs}ms;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colors('dark', '    ')}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${colors('dark', '  ')}
}

:root[data-theme="light"] {
  color-scheme: light;
}
`;
  },
});

// MARK: - JSON

StyleDictionary.registerFormat({
  name: 'briareus/json',
  format: ({ dictionary }) => {
    const tree = {};
    for (const t of dictionary.allTokens) {
      let node = tree;
      t.path.slice(0, -1).forEach((p) => (node = node[p] ??= {}));
      node[leaf(t)] = t.$extensions?.briareus?.statuses ? { role: value(t), statuses: t.$extensions.briareus.statuses } : value(t);
    }
    return JSON.stringify(tree, null, 2) + '\n';
  },
});

// MARK: - Build

const sd = new StyleDictionary({
  source: ['tokens/**/*.json'],
  usesDtcg: true,
  log: { warnings: 'error', verbosity: 'default' },
  platforms: {
    compose: {
      transforms: ['name/camel'], buildPath: 'dist/kotlin/',
      files: [{ destination: 'BriareusTokens.kt', format: 'briareus/compose', options: { packageName: 'com.okanetsolutions.briareus.tokens' } }],
    },
    swift: { transforms: ['name/camel'], buildPath: 'dist/swift/', files: [{ destination: 'BriareusTokens.swift', format: 'briareus/swift' }] },
    c: { transforms: ['name/camel'], buildPath: 'dist/c/', files: [{ destination: 'briareus_tokens.h', format: 'briareus/c' }] },
    css: { transforms: ['name/camel'], buildPath: 'dist/css/', files: [{ destination: 'briareus-tokens.css', format: 'briareus/css' }] },
    json: { transforms: ['name/camel'], buildPath: 'dist/json/', files: [{ destination: 'briareus-tokens.json', format: 'briareus/json' }] },
  },
});

await rm('dist', { recursive: true, force: true });
await sd.buildAllPlatforms();
