// Writes FEATURES.md from features/features.json: one table per area, a column per client.
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('..', import.meta.url);
const data = JSON.parse(await readFile(new URL('features/features.json', root), 'utf8'));
const NAMES = { windows: 'Windows', mac: 'Mac', ios: 'iPhone/iPad', quest: 'Quest' };
const MARK = { full: '●', partial: '◐', none: '·', 'n/a': '–' };

const all = data.areas.flatMap((a) => a.features);
const count = (client, level) => all.filter((f) => f.support[client] === level).length;
const cell = (text) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

let md = `<!-- Generated by scripts/features.mjs from features/features.json. Do not edit: change the JSON and run \`npm run build\`. -->
# What each client offers

${data.$description}

● full · ◐ partial · \`·\` none · – n/a (the platform cannot)

| | ${data.clients.map((c) => NAMES[c]).join(' | ')} |
| --- | ${data.clients.map(() => '---').join(' | ')} |
${['full', 'partial', 'none', 'n/a'].map((l) => `| ${MARK[l]} ${l} | ${data.clients.map((c) => count(c, l)).join(' | ')} |`).join('\n')}

`;

for (const area of data.areas) {
  md += `## ${area.title}\n\n| Feature | ${data.clients.map((c) => NAMES[c]).join(' | ')} | Notes |\n| --- | ${data.clients.map(() => ':---:').join(' | ')} | --- |\n`;
  for (const f of area.features) {
    const notes = Object.entries(f.notes ?? {}).map(([c, n]) => `**${NAMES[c]}:** ${cell(n)}`).join(' ');
    md += `| **${cell(f.title)}**<br>${cell(f.description)} | ${data.clients.map((c) => MARK[f.support[c]]).join(' | ')} | ${notes} |\n`;
  }
  md += '\n';
}

md += `## Server routes no client calls\n\n${data.unused_api.map((g) => `- **${g.group}:** ${g.routes.map((r) => `\`${r}\``).join(', ')}${g.note ? ` — ${g.note}` : ''}`).join('\n')}\n`;
await writeFile(new URL('FEATURES.md', root), md);
console.log(`FEATURES.md: ${all.length} features in ${data.areas.length} areas`);
